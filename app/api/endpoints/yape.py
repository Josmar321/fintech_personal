async def _get_admin_user(db: AsyncSession) -> User:
    if settings.TELEGRAM_CHAT_ID:
        result = await db.execute(
            select(User).where(
                User.telegram_chat_id == str(settings.TELEGRAM_CHAT_ID)
            )
        )
        user = result.scalar_one_or_none()
        if user:
            return user
    result = await db.execute(select(User).where(User.is_superuser == True))
    user = result.scalar_one_or_none()
    if user:
        return user
    result = await db.execute(select(User).order_by(User.id).limit(1))
    user = result.scalar_one_or_none()
    if user:
        return user
    logger.info("no_user_found_creating_default_admin")
    user = User(
        email="admin@local",
        password_hash="<auto-generated>",
        full_name="Admin",
        is_superuser=True,
        telegram_chat_id=str(settings.TELEGRAM_CHAT_ID) if settings.TELEGRAM_CHAT_ID else None,
    )
    db.add(user)
    await db.flush()
    return user


async def _get_or_create_yape_account(db: AsyncSession, user_id: int) -> Account:
    repo = AccountRepository(db)
    accounts = await repo.get_by_user_id(user_id)
    for a in accounts:
        if a.name == "Yape":
            return a
    account = Account(
        user_id=user_id,
        name="Yape",
        type=AccountType.CHECKING,
        currency="PEN",
    )
    db.add(account)
    await db.flush()
    return account


async def _create_yape_tx(
    tx_repo: TransactionRepository,
    user_id: int,
    account_id: int,
    tx: dict,
    is_income: bool,
    status: TransactionStatus,
    notes: str | None = None,
) -> dict | None:
    raw_str = json.dumps(tx, sort_keys=True, default=str)
    external_id = hashlib.sha256(raw_str.encode()).hexdigest()

    dup = await tx_repo.get_by_external_id(user_id, external_id)
    if dup:
        logger.info("yape_tx_skipped_dup", external_id=external_id, amount=tx.get("Monto"))
        return None

    mensaje = tx.get("Mensaje")
    desc = mensaje if mensaje else "Yape transaction"
    try:
        amount = Decimal(str(tx["Monto"])) if tx.get("Monto") else Decimal("0")
    except Exception:
        amount = Decimal("0")
    txn_date = _parse_date(tx.get("Fecha de operación"))

    txn = await tx_repo.create(
        user_id=user_id,
        account_id=account_id,
        description=desc,
        amount=amount,
        currency="PEN",
        notes=notes or (tx.get("Origen") if not mensaje else None),
        type=TransactionType.INCOME if is_income else TransactionType.EXPENSE,
        date=txn_date,
        source=TransactionSource.YAPE,
        status=status,
        raw_data=tx,
        external_id=external_id,
    )
    return {
        "id": txn.id,
        "amount": str(txn.amount),
        "description": txn.description,
        "type": str(txn.type),
    }


@router.post("/upload")
async def upload_yape_excel(
    file: UploadFile = File(...),
    db: AsyncSession = Depends(get_db),
):
    if not file.filename or not file.filename.endswith((".xlsx", ".xls")):
        return {"error": "File must be an Excel file (.xlsx or .xls)"}

    contents = await file.read()
    import tempfile
    with tempfile.NamedTemporaryFile(suffix=".xlsx", delete=False) as tmp:
        tmp.write(contents)
        temp_path = tmp.name

    df = read_yape_excel(temp_path)
    condo_keyword, remaining = route_transactions(df)

    filtered_condo: list[dict] = []
    for tx in condo_keyword:
        msg = str(tx.get("Mensaje", "")).lower()
        if any(kw in msg for kw in _ADMIN_INCOME_KEYWORDS):
            remaining.append(tx)
        else:
            filtered_condo.append(tx)
    condo_keyword = filtered_condo

    user = await _get_admin_user(db)
    yape_account = await _get_or_create_yape_account(db, user.id)
    tx_repo = TransactionRepository(db)

    condo_cat = await get_or_create_condominio_category(user.id, db)
    categorized_count = 0
    pending_ids: list[int] = []
    personal_pending_txs: list[dict] = []

    condo_candidates: list[dict] = []
    is_keyword: list[bool] = []

    for tx in condo_keyword:
        condo_candidates.append({**tx, "_fecha": _parse_date(tx.get("Fecha de operación"))})
        is_keyword.append(True)

    remaining_te_pago: list[dict] = []
    for tx in remaining:
        if str(tx.get("Tipo de Transacción", "")).strip() == "TE PAGÓ":
            condo_candidates.append({**tx, "_fecha": _parse_date(tx.get("Fecha de operación"))})
            is_keyword.append(False)
        else:
            remaining_te_pago.append(tx)

    batch_results = condo_sheets_service.batch_match_condo_payments(condo_candidates)

    condo_sheet = []
    condo_db = []
    personal_created = []
    skipped_count = 0

    for idx, (ok, msg) in enumerate(batch_results):
        raw_tx = condo_candidates[idx]
        tx = {k: v for k, v in raw_tx.items() if k != "_fecha"}
        if is_keyword[idx] and not ok:
            entry = await _create_yape_tx(
                tx_repo, user.id, yape_account.id, tx,
                is_income=True, status=TransactionStatus.FLAGGED,
                notes=f"Sheet: {msg}",
            )
            if entry:
                condo_db.append(entry)
            else:
                skipped_count += 1
        else:
            entry = await _create_yape_tx(
                tx_repo, user.id, yape_account.id, tx,
                is_income=True, status=TransactionStatus.CATEGORIZED,
                notes=f"Sheet: {'already paid' if ok else msg}",
            )
            if not entry:
                skipped_count += 1
                continue
            await tx_repo.update(entry["id"], category_id=condo_cat.id)
            categorized_count += 1
            if ok:
                condo_sheet.append({"transaction": tx, "ok": True, "msg": msg})

    for tx in remaining_te_pago:
        entry = await _create_yape_tx(
            tx_repo, user.id, yape_account.id, tx,
            is_income=False, status=TransactionStatus.PENDING_CONDO_VALIDATION,
        )
        if not entry:
            skipped_count += 1
            continue
        pending_ids.append(entry["id"])
        personal_pending_txs.append({
            "id": entry["id"], 
            "amount": str(entry["amount"]), 
            "description": entry.get("Mensaje", "Yape transaction"),
            "needs_condo_validation": True
        })
        personal_created.append(entry)

    await db.commit()

    if settings.TELEGRAM_CHAT_ID:
        flagged_txs = [
            {"id": e["id"], "amount": e["amount"], "description": e["description"]}
            for e in condo_db
        ]
        await send_yape_summary(
            chat_id=int(settings.TELEGRAM_CHAT_ID),
            filename=file.filename or "unknown",
            sheet_count=len(condo_sheet),
            flagged=flagged_txs,
            personal_count=len(personal_created),
            categorized_count=categorized_count,
            pending_ids=pending_ids,
            pending_personal_txs=personal_pending_txs,
            skipped_count=skipped_count,
            db_session=db,
        )

    return {
        "filename": file.filename,
        "total_rows": len(df),
        "skipped_duplicates": skipped_count,
        "condo_sheet": {"count": len(condo_sheet), "results": condo_sheet},
        "condo_db": {"count": len(condo_db), "created": condo_db},
        "personal": {"count": len(personal_created), "created": personal_created},
    }


@router.post("/confirm-sheet")
async def confirm_sheet_payments(
    body: dict,
    db: AsyncSession = Depends(get_db),
):
    tx_ids: list[int] = body.get("transaction_ids", [])
    if not tx_ids:
        return {"error": "transaction_ids required"}

    tx_repo = TransactionRepository(db)
    results: list[dict] = []

    for tx_id in tx_ids:
        txn = await tx_repo.get(tx_id)
        if not txn:
            results.append({"id": tx_id, "ok": False, "msg": "Transaction not found"})
            continue
        if txn.source != TransactionSource.YAPE:
            results.append({"id": tx_id, "ok": False, "msg": "Not a YAPE transaction"})
            continue

        raw = txn.raw_data or {}
        mensaje = str(raw.get("Mensaje", "") or "")
        monto = float(raw.get("Monto", 0) or 0)
        fecha = _parse_date(raw.get("Fecha de operación"))
        target_month = fecha.month - 1

        m = condo_sheets_service._APT_RE.search(mensaje)
        if not m:
            results.append({"id": tx_id, "ok": False, "msg": "No apartment number in message"})
            continue

        apt = m.group(1)
        ok, msg = condo_sheets_service.confirm_condo_payment(apt, monto, target_month)
        if ok:
            txn.status = TransactionStatus.CATEGORIZED
            db.add(txn)
            await db.flush()
        results.append({"id": tx_id, "ok": ok, "msg": msg})

    await db.commit()
    return {"results": results}


@router.post("/batch-categorize")
async def batch_categorize(
    body: dict,
    db: AsyncSession = Depends(get_db),
):
    ids: list[int] = body.get("ids", [])
    category_id: int | None = body.get("category_id")
    if not ids:
        return {"error": "ids required"}

    tx_repo = TransactionRepository(db)
    results: list[dict] = []

    for tx_id in ids:
        txn = await tx_repo.get(tx_id)
        if not txn:
            results.append({"id": tx_id, "ok": False, "msg": "Not found"})
            continue

        kwargs: dict = {"status": TransactionStatus.CATEGORIZED.value}
        if category_id is not None:
            kwargs["category_id"] = category_id
        await tx_repo.update(tx_id, **kwargs)
        results.append({"id": tx_id, "ok": True, "msg": "Categorized"})

    await db.commit()
    return {"results": results}


